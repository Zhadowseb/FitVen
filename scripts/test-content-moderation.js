const assert = require("assert");
const fs = require("fs");
const path = require("path");

const rootDir = path.resolve(__dirname, "..");

function read(...parts) {
  return fs.readFileSync(path.join(rootDir, ...parts), "utf8");
}

const migration = read(
  "supabase",
  "migrations",
  "20260912120000_content-moderation.sql"
);
const serviceSource = read("src", "Services", "moderationService.js");
const sheetSource = read(
  "src",
  "Resources",
  "Components",
  "ReportSheet",
  "ReportSheet.js"
);
const homeSource = read("src", "Pages", "HomePage", "HomePage.js");
const searchSource = read("src", "Pages", "SearchPage", "SearchPage.js");
const migrationsReadme = read("supabase", "migrations", "README.md");

/* -------------------------------------------------- the four requirements -- */

// Apple guideline 1.2 and Google Play's UGC policy. Blocking and the contact
// address already existed; these are the two this branch adds, and they are
// the reason the app can be submitted at all.
assert.match(migration, /create table if not exists public\.content_reports/);
assert.match(migration, /create table if not exists private\.blocked_terms/);

// A report is only useful if it can be acted on, so the reasons the app offers
// have to be reasons the column accepts.
const reasonIds = [...serviceSource.matchAll(/id: "([a-z_]+)"/g)].map(
  (match) => match[1]
);
const constraintBlock = migration.slice(
  migration.indexOf("content_reports_reason_valid"),
  migration.indexOf("content_reports_status_valid")
);

assert.ok(reasonIds.length >= 5, "expected the service to offer several reasons");

for (const reasonId of reasonIds) {
  assert.ok(
    constraintBlock.includes(`'${reasonId}'`),
    `reason "${reasonId}" is offered by the app but rejected by the check constraint`
  );
}

// A foreign key has to match the type of what it points at, and social_post.id
// is the one id in this schema that is not a uuid - it is `bigint generated by
// default as identity`. Declaring target_post_id as uuid was caught by
// Postgres rather than by anything here, which is why this check exists.
const socialPosts = read(
  "supabase",
  "migrations",
  "20260525142801_social-posts.sql"
);
const postIdType = socialPosts
  .slice(socialPosts.indexOf("create table if not exists public.social_post"))
  .match(/\bid ([a-z]+)/)?.[1];

assert.ok(postIdType, "could not read the type of social_post.id");
assert.match(
  migration,
  new RegExp("target_post_id " + postIdType + "\\b"),
  `target_post_id must be ${postIdType}, to match social_post.id`
);

/* ------------------------------------------------------- enforced server-side */

// The client writes to social_post directly, so a filter that only lives in
// JavaScript is a filter anybody can skip. Both triggers have to exist.
assert.match(
  migration,
  /create trigger reject_blocked_post_text[\s\S]*before insert or update of title, body on public\.social_post/
);
assert.match(
  migration,
  /create trigger reject_blocked_profile_text[\s\S]*on public\.profiles/
);

// Hiding a reported post is what turns a report into a response. The feed
// policy has to respect it, or the post is only hidden from whoever looks.
assert.match(migration, /add column if not exists hidden_at timestamptz/);
assert.match(
  migration,
  /create policy "Social posts are viewable by owners and allowed audience"[\s\S]*hidden_at is null/
);
assert.match(migration, /create trigger hide_post_when_reported/);

// Nobody may read anybody else's reports, and no policy may grant it.
assert.match(
  migration,
  /create policy "Users can read their own reports"[\s\S]*using \(\(select auth\.uid\(\)\) = reporter_id\)/
);
assert.doesNotMatch(migration, /grant (select|all)[^;]*content_reports[^;]*anon/);

// The list itself is never readable by a client: a client that can read it can
// work around it.
assert.ok(
  migration.includes("private.blocked_terms"),
  "the term list must live in the private schema"
);
assert.doesNotMatch(migration, /grant[^;]*private\.blocked_terms[^;]*authenticated/);

// The check the app calls answers yes or no and never says which word.
assert.match(migration, /create or replace function public\.is_text_allowed/);
// The client asks the yes/no function and never reads the list itself.
assert.match(serviceSource, /supabase\.rpc\("is_text_allowed"/);
assert.ok(
  !serviceSource.includes("blocked_terms"),
  "the client must never read the term list"
);

/* ------------------------------------------------------------- reachability */

// Reporting has to be reachable from the content, not buried in settings.
assert.match(homeSource, /onOpenOptions=\{handleOpenWorkoutSummaryOptions\}/);
assert.match(homeSource, /Report post/);
assert.match(homeSource, /<ReportSheet/);
assert.match(searchSource, /<ReportSheet/);
assert.match(searchSource, /Report \$\{relationshipProfile\.displayName\}/);

// Blocking is offered in the same breath as reporting: someone who reports a
// person usually wants to stop seeing them, and a second screen is where the
// second half goes undone.
assert.match(sheetSource, /socialService\.blockUser/);
assert.match(sheetSource, /Also block/);

// A failed block must not take the report down with it.
assert.match(
  sheetSource,
  /if \(alsoBlock && canBlock\) \{[\s\S]*try \{[\s\S]*catch \(blockError\)/
);

// The ledger has to say whether the migration has been run. This one has not,
// and saying so is the point.
assert.match(
  migrationsReadme,
  /`20260912120000_content-moderation\.sql` \| \*\*no/
);

console.log(
  "Content moderation: reasons match the constraint, filtering and hiding are enforced in the database, reporting is reachable from the content."
);
