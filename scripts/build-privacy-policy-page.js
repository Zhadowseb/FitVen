#!/usr/bin/env node
// Writes docs/privacy-policy.html from src/Resources/Legal/privacyPolicy.js.
//
// Google Play requires the policy at a public address, and the app shows it on
// a screen. Those are two copies of a legal document, and two copies drift -
// somebody edits the app text, the hosted page still says something else, and
// which one a user agreed to becomes an open question. So the hosted page is
// generated, never edited, and npm test fails if it is out of date.
//
// Run with --check to compare instead of write.

const path = require("path");
const fs = require("fs");
const loadAppModule = require("./lib/loadAppModule");

const root = path.resolve(__dirname, "..");
const outputFile = path.join(root, "docs", "privacy-policy.html");

const {
  PRIVACY_POLICY_LAST_UPDATED,
  PRIVACY_POLICY_SECTIONS,
  PRIVACY_POLICY_VERSION,
} = loadAppModule("src/Resources/Legal/privacyPolicy.js");

function escapeHtml(text) {
  return String(text)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function renderBody(body) {
  return String(body)
    .split(/\n{2,}/)
    .map((paragraph) => paragraph.trim())
    .filter(Boolean)
    .map((paragraph) => `      <p>${escapeHtml(paragraph)}</p>`)
    .join("\n");
}

const sections = PRIVACY_POLICY_SECTIONS.map(
  (section) => `    <section>
      <h2>${escapeHtml(section.title)}</h2>
${renderBody(section.body)}
    </section>`
).join("\n\n");

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>FitVen — Privacy</title>
<!--
  Generated by scripts/build-privacy-policy-page.js. Do not edit.
  Change src/Resources/Legal/privacyPolicy.js and run:
    npm run build:privacy-policy
-->
<style>
  :root {
    color-scheme: light dark;
    --ink: #16181d;
    --quiet: #5c626e;
    --ground: #ffffff;
    --rule: #e3e6eb;
  }
  @media (prefers-color-scheme: dark) {
    :root {
      --ink: #edeff3;
      --quiet: #a2a9b6;
      --ground: #121419;
      --rule: #2a2e37;
    }
  }
  body {
    margin: 0;
    padding: 40px 20px 64px;
    background: var(--ground);
    color: var(--ink);
    font: 16px/1.6 -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
  }
  main { max-width: 680px; margin: 0 auto; }
  h1 { font-size: 28px; margin: 0 0 4px; }
  h2 { font-size: 18px; margin: 0 0 8px; }
  section { padding: 24px 0; border-top: 1px solid var(--rule); }
  section:first-of-type { border-top: 0; }
  p { margin: 0 0 12px; }
  p:last-child { margin-bottom: 0; }
  .meta { color: var(--quiet); font-size: 14px; margin: 0 0 8px; }
</style>
</head>
<body>
  <main>
    <h1>FitVen — Privacy</h1>
    <p class="meta">Version ${escapeHtml(
      PRIVACY_POLICY_VERSION
    )} · Last updated ${escapeHtml(PRIVACY_POLICY_LAST_UPDATED)}</p>

${sections}
  </main>
</body>
</html>
`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outputFile)
    ? fs.readFileSync(outputFile, "utf8")
    : null;

  if (current === null) {
    console.error(
      "docs/privacy-policy.html is missing. Run: npm run build:privacy-policy"
    );
    process.exit(1);
  }

  // Normalised, because git rewrites the line endings on this repo.
  if (current.replace(/\r\n/g, "\n") !== html.replace(/\r\n/g, "\n")) {
    console.error(
      "docs/privacy-policy.html no longer matches the policy the app shows.\n" +
        "The hosted copy and the in-app copy must say the same thing.\n" +
        "Run: npm run build:privacy-policy"
    );
    process.exit(1);
  }

  console.log("Privacy policy page matches the app text.");
  process.exit(0);
}

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(outputFile, html);
console.log(`Wrote ${path.relative(root, outputFile).split(path.sep).join("/")}`);
