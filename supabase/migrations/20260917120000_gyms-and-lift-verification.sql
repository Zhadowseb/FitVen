/* ---------------------------------------------------- national_strongest -- */

-- Top verified lift per featured exercise across every centre, for the card
-- on the Centres screen.
create or replace function public.national_strongest()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  with viewer as (
    select auth.uid() as id
  ),
  home as (
    select private.home_gym_id_for((select id from viewer)) as gym_id
  ),
  ranked as (
    select * from private.ranked_lifts((select id from viewer), null, null, 'gym', 'kg')
  )
  select coalesce(jsonb_agg(
    jsonb_build_object(
      'exercise_id', fe.exercise_id,
      'exercise_name', fe.exercise_name,
      'top', (
        select r.row_json || jsonb_build_object('is_home_gym', r.gym_id = (select gym_id from home))
        from ranked r
        where r.exercise_id = fe.exercise_id and r.rank = 1
        order by r.performed_at asc, r.lift_id asc
        limit 1
      )
    )
    order by fe.sort_order
  ), '[]'::jsonb)
  from private.featured_exercises() fe
  where (select id from viewer) is not null;
$$;

