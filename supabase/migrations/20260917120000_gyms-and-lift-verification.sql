-- Centres, workout -> centre matching, per-centre lift leaderboards and lift
-- video verification.
--
-- Run after:
--   supabase/migrations/20260916210000_opt-in-column-defaults.sql
--
-- A centre is a public fitness centre with a chain, a name, an address,
-- coordinates and a hero image. The rows come from `npm run gyms:import`, which
-- reads data/gyms/ and runs with the service role - app users only read them.
--
-- A workout belongs to a centre when the client matched its start position to
-- one (match_gym). The best set per exercise of a finished strength workout in
-- a centre lands in gym_lift, one row per (user, centre, exercise), and that is
-- what the leaderboards rank. Every leaderboard read goes through a security
-- definer function below rather than a table policy, for two reasons:
--   * ranking needs other people's profiles, which public.profiles no longer
--     answers for strangers, and
--   * blocks have to be filtered, and src/AGENTS.md is explicit that a block
--     check in an RLS expression silently passes - it has to be a security
--     definer function.
-- gym_lift therefore has an own-rows-only select policy; the functions are the
-- public surface.

