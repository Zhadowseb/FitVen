-- Centres the viewer has trained in over the last 90 days, most often first.
create or replace function public.my_gyms()
returns table (
  id bigint,
  chain text,
  name text,
  short_name text,
  city text,
  image_url text,
  workout_count integer,
  is_home_gym boolean
)
language sql
stable
security definer
set search_path = ''
as $$
  with viewer as (
    select auth.uid() as id
  ),
  counts as (
    select workout.gym_id, count(*)::integer as workout_count
    from public.workout_type_instance workout
    where workout.user_id = (select id from viewer)
      and workout.gym_id is not null
      and workout.done = true
      and workout.deleted_at is null
      and workout.date::date >= current_date - 90
    group by workout.gym_id
  )
  select
    gym.id,
    gym.chain,
    gym.name,
    gym.short_name,
    gym.city,
    gym.image_url,
    counts.workout_count,
    gym.id = private.home_gym_id_for((select id from viewer)) as is_home_gym
  from counts
  join public.gym gym on gym.id = counts.gym_id
  where (select id from viewer) is not null
  order by counts.workout_count desc, gym.short_name asc;
$$;

revoke all on function public.my_gyms() from public, anon;
grant execute on function public.my_gyms() to authenticated;

