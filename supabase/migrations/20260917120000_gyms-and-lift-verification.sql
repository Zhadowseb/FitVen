-- Recount after every vote. Two rejections beat any number of approvals.
create or replace function private.gym_lift_vote_recount()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_lift_id bigint := coalesce(new.lift_id, old.lift_id);
  approval_count integer;
  rejection_count integer;
begin
  if current_setting('fitven.gym_lift_skip_recount', true) = 'on' then
    return null;
  end if;

  select
    count(*) filter (where vote.approve),
    count(*) filter (where not vote.approve)
  into approval_count, rejection_count
  from public.gym_lift_vote vote
  where vote.lift_id = target_lift_id;

  perform set_config('fitven.gym_lift_recount', 'on', true);

  update public.gym_lift
  set approvals = approval_count,
      rejections = rejection_count,
      video_status = case
        when video_path is null then 'none'
        when rejection_count >= 2 then 'rejected'
        when approval_count >= 3 then 'verified'
        else 'pending'
      end
  where id = target_lift_id;

  perform set_config('fitven.gym_lift_recount', 'off', true);

  return null;
end;
$$;

drop trigger if exists gym_lift_vote_recount on public.gym_lift_vote;
create trigger gym_lift_vote_recount
after insert or delete on public.gym_lift_vote
for each row execute function private.gym_lift_vote_recount();

