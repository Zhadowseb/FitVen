returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  new.approvals := 0;
  new.rejections := 0;
  new.previous_weight_kg := null;
  new.video_status := case when new.video_path is null then 'none' else 'pending' end;
  new.created_at := timezone('utc', now());
