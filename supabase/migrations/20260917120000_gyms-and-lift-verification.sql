-- Who may vote: not the lifter, somebody who trains at the same centre, and
-- nobody on either side of a block. Security definer because the lift row and
-- the other person's workouts are not the voter's to read.
create or replace function private.gym_lift_vote_before_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  lift public.gym_lift%rowtype;
begin
  select * into lift from public.gym_lift where id = new.lift_id;

  if not found then
    raise exception 'That lift no longer exists.' using errcode = '23503';
  end if;

  if lift.user_id = new.voter_id then
    raise exception 'You cannot vote on your own lift.' using errcode = '42501';
  end if;

  if lift.video_path is null then
    raise exception 'This lift has no video to review.' using errcode = '23514';
  end if;

  if private.blocked_between(lift.user_id, new.voter_id) then
    raise exception 'That lift is not available.' using errcode = '42501';
  end if;

  if not private.trains_at_gym(new.voter_id, lift.gym_id) then
    raise exception 'Only people who train at this centre can vote on its lifts.' using errcode = '42501';
  end if;

  if new.approve then
    new.reason := null;
  elsif new.reason is null then
    new.reason := 'other';
  end if;

  new.created_at := timezone('utc', now());
  return new;
end;
$$;

