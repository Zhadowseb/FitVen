-- The one place the ranking rules live. Every leaderboard function selects
-- from this. Rows the viewer must not see (blocked either way, rejected and
-- not their own) are already gone; rank is computed over what remains, and a
-- rejected row of the viewer's own comes back with a null rank so the screen
-- can still show it to them.
--
--   target_gym_id  null for the whole country, which also forces verified only
--   scope          'gym' or 'friends' (people the viewer follows, plus the viewer)
--   unit           'kg' or 'bw' (weight over bodyweight; rows without one drop)
create or replace function private.ranked_lifts(
  viewer_id uuid,
  target_gym_id bigint,
  target_exercise_id bigint,
  scope text,
  unit text
)
returns table (
  lift_id bigint,
  rank bigint,
  user_id uuid,
  display_name text,
  avatar_path text,
  gym_id bigint,
  gym_short_name text,
  gym_city text,
  exercise_id bigint,
  exercise_name text,
  weight_kg numeric,
  reps integer,
  bodyweight_kg numeric,
  ratio numeric,
  sort_key numeric,
  video_status text,
  approvals integer,
  rejections integer,
  performed_at timestamptz,
  previous_weight_kg numeric,
  is_me boolean,
  row_json jsonb
)
language sql
stable
security definer
set search_path = ''
as $$
  with visible as (
    select
      lift.*,
      profile.display_name,
      profile.avatar_path,
      gym.short_name as gym_short_name,
      gym.city as gym_city,
      case
        when lift.bodyweight_kg is not null and lift.bodyweight_kg > 0
          then round(lift.weight_kg / lift.bodyweight_kg, 3)
        else null
      end as ratio
    from public.gym_lift lift
    join public.profiles profile on profile.id = lift.user_id
    join public.gym gym on gym.id = lift.gym_id
    where (target_gym_id is null or lift.gym_id = target_gym_id)
      and (target_exercise_id is null or lift.exercise_id = target_exercise_id)
      and gym.is_public
      and (
        lift.user_id = viewer_id
        or (
          lift.video_status <> 'rejected'
          and not private.blocked_between(viewer_id, lift.user_id)
        )
      )
      and (target_gym_id is not null or lift.video_status = 'verified')
      and (
        coalesce(scope, 'gym') <> 'friends'
        or lift.user_id = viewer_id
        or exists (
          select 1
          from public.user_follows follow
          where follow.follower_id = viewer_id
            and follow.following_id = lift.user_id
        )
      )
      and (coalesce(unit, 'kg') <> 'bw' or lift.bodyweight_kg is not null)
  ),
  ranked as (
    select
      visible.*,
      case when coalesce(unit, 'kg') = 'bw' then visible.ratio else visible.weight_kg end as sort_key,
      case
        when visible.video_status = 'rejected' then null
        else rank() over (
          partition by visible.exercise_id
          order by
            case when visible.video_status = 'rejected' then 1 else 0 end,
            case when coalesce(unit, 'kg') = 'bw' then visible.ratio else visible.weight_kg end desc,
            visible.performed_at asc,
            visible.id asc
        )
      end as rank
    from visible
  )
  select
    ranked.id,
    ranked.rank,
    ranked.user_id,
    ranked.display_name,
    ranked.avatar_path,
    ranked.gym_id,
    ranked.gym_short_name,
    ranked.gym_city,
    ranked.exercise_id,
    ranked.exercise_name,
    ranked.weight_kg,
    ranked.reps,
    ranked.bodyweight_kg,
    ranked.ratio,
    ranked.sort_key,
    ranked.video_status,
    ranked.approvals,
    ranked.rejections,
    ranked.performed_at,
    ranked.previous_weight_kg,
    ranked.user_id = viewer_id as is_me,
    -- The row as the client receives it. Built here, once, so every function
    -- below hands out the same shape.
    jsonb_build_object(
      'lift_id', ranked.id,
      'rank', ranked.rank,
      'user_id', ranked.user_id,
      'display_name', ranked.display_name,
      'avatar_path', ranked.avatar_path,
      'gym', jsonb_build_object('id', ranked.gym_id, 'short_name', ranked.gym_short_name, 'city', ranked.gym_city),
      'exercise_id', ranked.exercise_id,
      'exercise_name', ranked.exercise_name,
      'weight_kg', ranked.weight_kg,
      'reps', ranked.reps,
      'bodyweight_kg', ranked.bodyweight_kg,
      'ratio', ranked.ratio,
      'video_status', ranked.video_status,
      'approvals', ranked.approvals,
      'rejections', ranked.rejections,
      'performed_at', ranked.performed_at,
      'previous_weight_kg', ranked.previous_weight_kg,
      'is_me', ranked.user_id = viewer_id
    ) as row_json
  from ranked;
$$;

/* ------------------------------------------- gym_leaderboard_overview -- */

create or replace function public.gym_leaderboard_overview(
  target_gym_id bigint,
  scope text default 'gym',
  more_limit integer default 8
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  viewer_id uuid := auth.uid();
  gym_json jsonb;
  featured_json jsonb;
  more_json jsonb;
  more_total integer;
begin
  if viewer_id is null then
    return null;
  end if;

  gym_json := private.gym_summary(target_gym_id, viewer_id);

  if gym_json is null then
    return null;
  end if;

  with ranked as (
    select * from private.ranked_lifts(viewer_id, target_gym_id, null, scope, 'kg')
  ),
  featured as (
    select
      fe.exercise_id,
      fe.exercise_name,
      fe.sort_order,
      (select count(*) from ranked r where r.exercise_id = fe.exercise_id and r.rank is not null) as lifter_count,
      (select r.row_json from ranked r where r.exercise_id = fe.exercise_id and r.rank = 1 order by r.performed_at asc, r.lift_id asc limit 1) as top,
      (select r.row_json from ranked r where r.exercise_id = fe.exercise_id and r.is_me limit 1) as me
    from private.featured_exercises() fe
  )
  select coalesce(jsonb_agg(
    jsonb_build_object(
      'exercise_id', featured.exercise_id,
      'exercise_name', featured.exercise_name,
      'lifter_count', featured.lifter_count,
      'top', featured.top,
      'me', case
        when featured.me is null then null
        else featured.me || jsonb_build_object(
          'gap_to_top',
          case
            when featured.top is null then null
            else (featured.top ->> 'weight_kg')::numeric - (featured.me ->> 'weight_kg')::numeric
          end
        )
      end
    )
    order by featured.sort_order
  ), '[]'::jsonb)
  into featured_json
  from featured;

  with ranked as (
    select * from private.ranked_lifts(viewer_id, target_gym_id, null, scope, 'kg')
  ),
  others as (
    select
      r.exercise_id,
      max(r.exercise_name) as exercise_name,
      count(*) filter (where r.rank is not null) as lifter_count,
      (array_agg(r.display_name order by r.rank asc nulls last, r.performed_at asc))[1] as top_name,
      (array_agg(r.weight_kg order by r.rank asc nulls last, r.performed_at asc))[1] as top_weight_kg,
      max(r.rank) filter (where r.is_me) as my_rank
    from ranked r
    where r.exercise_id not in (select fe.exercise_id from private.featured_exercises() fe)
    group by r.exercise_id
  ),
  numbered as (
    select others.*, row_number() over (order by others.lifter_count desc, others.exercise_name asc) as row_number
    from others
  )
  select
    count(*)::integer,
    coalesce(jsonb_agg(
      jsonb_build_object(
        'exercise_id', numbered.exercise_id,
        'exercise_name', numbered.exercise_name,
        'lifter_count', numbered.lifter_count,
        'top_name', numbered.top_name,
        'top_weight_kg', numbered.top_weight_kg,
        'my_rank', numbered.my_rank
      )
      order by numbered.row_number
    ) filter (where more_limit is null or numbered.row_number <= more_limit), '[]'::jsonb)
  into more_total, more_json
  from numbered;

  return jsonb_build_object(
    'gym', gym_json,
    'scope', coalesce(scope, 'gym'),
    'featured', featured_json,
    'more', more_json,
    'more_total', more_total
  );
end;
$$;

revoke all on function public.gym_leaderboard_overview(bigint, text, integer) from public, anon;
grant execute on function public.gym_leaderboard_overview(bigint, text, integer) to authenticated;

/* ------------------------------------------- gym_exercise_leaderboard -- */

-- One page of a ranked list plus the viewer's own row. The cursor is the last
-- row's (sort_key, performed_at, lift_id); pass them back to get the next page.
-- With target_gym_id null it is the whole country, verified lifts only.
create or replace function public.gym_exercise_leaderboard(
  target_gym_id bigint,
  target_exercise_id bigint,
  scope text default 'gym',
  unit text default 'kg',
  page_limit integer default 50,
  cursor_sort_key numeric default null,
  cursor_performed_at timestamptz default null,
  cursor_id bigint default null
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  viewer_id uuid := auth.uid();
  safe_limit integer := least(greatest(coalesce(page_limit, 50), 1), 100);
  rows_json jsonb;
  me_json jsonb;
  total_count integer;
  exercise_json jsonb;
  last_sort_key numeric;
  last_performed_at timestamptz;
  last_lift_id bigint;
  next_cursor jsonb := null;
begin
  if viewer_id is null then
    return null;
  end if;

  select jsonb_build_object('id', exercise.id, 'name', exercise.name)
  into exercise_json
  from public."Exercise" exercise
  where exercise.id = target_exercise_id;

  with ranked as (
    select * from private.ranked_lifts(viewer_id, target_gym_id, target_exercise_id, scope, unit)
  ),
  page as (
    select r.*
    from ranked r
    where r.rank is not null
      and (
        cursor_sort_key is null
        or r.sort_key < cursor_sort_key
        or (r.sort_key = cursor_sort_key and r.performed_at > cursor_performed_at)
        or (r.sort_key = cursor_sort_key and r.performed_at = cursor_performed_at and r.lift_id > cursor_id)
      )
    order by r.sort_key desc, r.performed_at asc, r.lift_id asc
    limit safe_limit
  )
  select
    (select count(*)::integer from ranked r where r.rank is not null),
    (select r.row_json from ranked r where r.is_me limit 1),
    coalesce((select jsonb_agg(page.row_json order by page.sort_key desc, page.performed_at asc, page.lift_id asc) from page), '[]'::jsonb),
    (select page.sort_key from page order by page.sort_key asc, page.performed_at desc, page.lift_id desc limit 1),
    (select page.performed_at from page order by page.sort_key asc, page.performed_at desc, page.lift_id desc limit 1),
    (select page.lift_id from page order by page.sort_key asc, page.performed_at desc, page.lift_id desc limit 1)
  into total_count, me_json, rows_json, last_sort_key, last_performed_at, last_lift_id;

  if jsonb_array_length(rows_json) = safe_limit then
    next_cursor := jsonb_build_object(
      'sort_key', last_sort_key,
      'performed_at', last_performed_at,
      'lift_id', last_lift_id
    );
  end if;

  return jsonb_build_object(
    'gym', case when target_gym_id is null then null else private.gym_summary(target_gym_id, viewer_id) end,
    'exercise', exercise_json,
    'scope', coalesce(scope, 'gym'),
    'unit', coalesce(unit, 'kg'),
    'total', total_count,
    'rows', rows_json,
    'me', me_json,
    'next_cursor', next_cursor
  );
end;
$$;

revoke all on function public.gym_exercise_leaderboard(bigint, bigint, text, text, integer, numeric, timestamptz, bigint) from public, anon;
grant execute on function public.gym_exercise_leaderboard(bigint, bigint, text, text, integer, numeric, timestamptz, bigint) to authenticated;

