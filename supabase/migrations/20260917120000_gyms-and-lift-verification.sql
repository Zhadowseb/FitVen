/* ------------------------------------------------------------ match_gym -- */

-- Nearest public centre within its own match radius, or nothing. The
-- bounding box is what the (latitude, longitude) index answers; the haversine
-- runs on those few rows.
create or replace function public.match_gym(lat double precision, lng double precision)
returns setof public.gym
language sql
stable
security definer
set search_path = ''
as $$
  with candidates as (
    select
      gym.*,
      2 * 6371000 * asin(sqrt(
        power(sin(radians(gym.latitude - lat) / 2), 2)
        + cos(radians(lat)) * cos(radians(gym.latitude))
          * power(sin(radians(gym.longitude - lng) / 2), 2)
      )) as distance_m
    from public.gym gym
    where gym.is_public
      and gym.latitude between lat - 0.01 and lat + 0.01
      and gym.longitude between lng - 0.02 and lng + 0.02
  )
  select gym.*
  from public.gym gym
  where gym.id = (
    select candidates.id
    from candidates
    where candidates.distance_m <= candidates.match_radius_m
    order by candidates.distance_m asc
    limit 1
  );
$$;

revoke all on function public.match_gym(double precision, double precision) from public, anon;
grant execute on function public.match_gym(double precision, double precision) to authenticated;

/* ---------------------------------------------------------- gyms_nearby -- */

create or replace function public.gyms_nearby(
  lat double precision,
  lng double precision,
  result_limit integer default 20
)
returns table (
  id bigint,
  chain text,
  name text,
  short_name text,
  address text,
  city text,
  latitude double precision,
  longitude double precision,
  image_url text,
  distance_m double precision,
  member_count integer,
  is_home_gym boolean
)
language sql
stable
security definer
set search_path = ''
as $$
  with viewer as (
    select auth.uid() as id
  ),
  home as (
    select private.home_gym_id_for((select id from viewer)) as gym_id
  )
  select
    gym.id,
    gym.chain,
    gym.name,
    gym.short_name,
    gym.address,
    gym.city,
    gym.latitude,
    gym.longitude,
    gym.image_url,
    2 * 6371000 * asin(sqrt(
      power(sin(radians(gym.latitude - lat) / 2), 2)
      + cos(radians(lat)) * cos(radians(gym.latitude))
        * power(sin(radians(gym.longitude - lng) / 2), 2)
    )) as distance_m,
    private.gym_member_count(gym.id) as member_count,
    gym.id = (select gym_id from home) as is_home_gym
  from public.gym gym
  where gym.is_public
    and (select id from viewer) is not null
  order by distance_m asc
  limit least(greatest(coalesce(result_limit, 20), 1), 100);
$$;

